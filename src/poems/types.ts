/* Types for a matn: how it is registered (PoemConfig, in code) and how its text
   is stored (PoemDoc, in R2 under data/poem/<id>.json).

   The split is deliberate. Registering a matn is a code change — it declares
   the URL, the verse count every upload is checked against, and which reading
   features the page switches on. The text itself is content: imported once
   through /admin/import, then edited in the Bayt and Content editors, with no
   deploy in between. */

/** The accent palettes defined in src/styles/theme.css (body.matn-<accent>). */
export const ACCENTS = ['madder', 'lapis', 'verdigris', 'indigo', 'plum', 'sienna', 'teal'] as const;
export type Accent = (typeof ACCENTS)[number];

export interface PoemConfig {
  /** URL slug and storage key: lowercase latin letters, digits and dashes.
      The reading page is served at /<id>. */
  id: string;
  /** Arabic title, fully vowelled, as the hero shows it. */
  titleAr: string;
  /** Short Arabic name for the nav bar, the matn switcher and the app tabs. */
  shortAr: string;
  /** Full transliterated title, e.g. "Al-Muqaddimah al-Jazariyyah". */
  titleEn: string;
  /** Short transliterated name, e.g. "Jazariyyah". */
  shortEn: string;
  /** One or two sentences: the hero subtitle and the page's meta description. */
  description: string;
  /** Eyebrow above the hero title, after the collection name ("The Science of Tajwīd"). */
  subject?: string;
  author?: { name: string; died?: string };
  /** Poetic metre, shown as a chip under the title. */
  metre?: string;
  /** The number of abyāt. Every write of this matn is checked against it. */
  verses: number;
  accent: Accent;
  /** The closing line printed in the page footer. */
  closing?: { ar: string; en?: string };

  /** Draft mutūn are built and reachable by URL (so they can be proofed on the
      live site) but are left out of the home page, menus, sitemap and the
      offline precache, and are served noindex. */
  draft?: boolean;

  /* ── features ─────────────────────────────────────────────────────────── */
  explanations?: {
    /** Attribution under a card that records none of its own. */
    by?: string;
    /** Whether an explanation shows before anyone has switched it on in the
        content editor: 'on' for commentary already checked, 'off' (the
        default) keeps every card hidden until it has been reviewed. */
    defaultOn?: boolean;
    /** Which abyāt may carry one. Default: all of them. */
    bayts?: number[];
  };
  /** Editions of the matn. With two or more, readers get a picker in the ⋯
      menu and a ⇄ compare button on every bayt that differs; the wording of
      edition 2+ is stored on the document as `variants`. */
  nuskhas?: string[];
  /** Which edition (1-based) the recitations follow. Default 1. */
  audioNuskha?: number;
  /** Labels for verses carrying `kind` (word-list abyāt shown without a
      translation line), e.g. { zah: 'List of ẓāʾ words' }. */
  kindLabels?: Record<string, string>;
  /** Set the Arabic quoted inside Urdu translations in the Arabic face. */
  arabicInUrdu?: boolean;
  /** Qirāʾāt panels (the mushaf button under a bayt), stored at data/qiraat/<id>.json. */
  qiraat?: boolean;
  /** Attribution printed under every qirāʾāt panel — the sharḥ the readings
      are sourced from, e.g. "al-Wāfī fī Sharḥ al-Shāṭibiyyah · الوافي في شرح الشاطبية". */
  qiraatSource?: string;
  /** Downloadable PDFs, generated by `npm run pdf` into public/pdf/<id>/. */
  pdf?: { whole?: boolean; chapters?: boolean };
}

/* ── stored document ───────────────────────────────────────────────────── */

/** One word of a hemistich: the text (may carry ramz markup) and its glosses. */
export interface WordCell {
  w: string;
  /** English gloss. */
  g?: string;
  /** Urdu gloss. */
  gu?: string;
  /** Footnote on a variant reading of this word. */
  fn?: string;
}

export type ExpLang = 'en' | 'ur' | 'ar';
/** An explanation: one English string, or the same note in up to three languages. */
export type Explanation = string | Partial<Record<ExpLang, string>>;

export interface Verse {
  n: number;
  sadr: string;
  ajuz: string;
  sadrW?: WordCell[] | null;
  ajuzW?: WordCell[] | null;
  /** Word indexes (0-based) set in red ink, when the hemistich has no cells. */
  sr?: number[] | null;
  jr?: number[] | null;
  tr?: string;
  ur?: string;
  exp?: Explanation;
  expBy?: string;
  /** A word-list bayt; see PoemConfig.kindLabels. */
  kind?: string;
}

export interface Chapter {
  i: number;
  ar: string;
  en?: string;
  tr?: string;
  desc?: string;
  note?: string;
  verses: Verse[];
}

/** Edition 2+ wording for one bayt. Omitted word cells/red-word indexes are
    dropped for that bayt, so a gloss can never disagree with the text shown. */
export type VerseVariant = Partial<Pick<Verse, 'sadr' | 'ajuz' | 'sadrW' | 'ajuzW' | 'sr' | 'jr' | 'tr' | 'exp'>>;

export interface PoemDoc {
  id: string;
  version: number;
  updatedAt: string | null;
  chapters: Chapter[];
  /** Keyed by edition number ("2", "3", …), then by bayt number. */
  variants?: Record<string, Record<string, VerseVariant>>;
  /** Set on a document served from a bundled seed rather than storage. */
  source?: string;
}

/* ── qirāʾāt ───────────────────────────────────────────────────────────── */

export type QxText = string | Partial<Record<'ar' | 'en' | 'ur', string>>;
export interface QxReading { who: QxText; how: QxText; note?: QxText; hafs?: boolean }
export interface QxExampleCard {
  word: QxText; scope?: QxText; sura?: QxText; ayah?: number; ayahText?: string;
  readings: QxReading[];
}
export interface QxRuleCard {
  rule: { kind?: 'rule' | 'explain'; title: QxText; statement: QxText; conditions?: QxText[]; caution?: QxText[] };
  readings?: QxReading[];
  examples?: { word?: QxText; case?: QxText; sura?: QxText; ayah?: number; ayahText?: string }[];
}
export type QxCard = QxExampleCard | QxRuleCard;

export interface QiraatDoc {
  id: string;
  version: number;
  updatedAt: string | null;
  examples: Record<string, QxCard[]>;
}
export interface QiraatIndex { id: string; version: number; updatedAt: string | null; bayts: number[] }

/* ── visibility switches ──────────────────────────────────────────────── */

/** Per-bayt switches set in the content editor (stored at switches/<id>.json). */
export interface Switches {
  /** Explanation panel SHOWN. Missing = hidden (the accuracy gate). */
  enabled: Record<string, boolean>;
  /** English translation HIDDEN. Missing = shown. */
  trHidden: Record<string, boolean>;
  /** Urdu translation HIDDEN. Missing = shown. */
  urHidden: Record<string, boolean>;
}

/* ── API shapes shared by the worker and the pages ─────────────────────── */

export interface ManifestEntry { version: number; updatedAt: string | null }
export interface Manifest {
  ok: true;
  /** Changes whenever any dataset does; clients compare per entry. */
  version: number;
  updatedAt: string | null;
  poems: Record<string, ManifestEntry>;
  qiraat: Record<string, ManifestEntry>;
  source?: 'unavailable';
}

export interface AudioReciter {
  id: string;
  name: string;
  abyat: number[];
  /** bayt → playable URL (same origin, under /media/). */
  urls: Record<string, string>;
  /** Total download weight, so the offline manager can say what it will save. */
  bytes: number;
}
export interface AudioManifest { ok: true; poem: string; reciters: AudioReciter[] }

export interface Reciter { id: string; name: string }
