/* Build-time output that is derived rather than written by hand, all from
   src/config/site.ts and the poem registry:

     dist/_headers     caching, security and noindex rules for the static assets
     dist/_redirects   the short links (/android, /ios, …) that are configured
     dist/sw.js        the service worker, with its precache list and version
                       computed from the files actually built

   The service worker's version is a hash of every precached file, so any
   change to the shell ships a new worker and installed apps pick it up after a
   restart — there is no CACHE_VERSION to remember to bump. */
import type { AstroIntegration } from 'astro';
import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import { SITE } from '../src/config/site.ts';
import { ALL_POEMS, POEMS } from '../src/poems/index.ts';

const NOINDEX = '  X-Robots-Tag: noindex, nofollow';

async function walk(dir: string): Promise<string[]> {
  const out: string[] = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) out.push(...(await walk(p)));
    else out.push(p);
  }
  return out;
}

/** dist/x.html → /x, dist/index.html → / */
function urlOf(rel: string): string {
  const p = '/' + rel.split(sep).join('/');
  if (p === '/index.html') return '/';
  return p.endsWith('.html') ? p.slice(0, -5) : p;
}

function headersFile(): string {
  const blocks: string[] = [
    '# Generated by integrations/site-output.ts — edit that file, not this one.',
    '/*\n  X-Content-Type-Options: nosniff\n  Referrer-Policy: strict-origin-when-cross-origin',
    '/_astro/*\n  Cache-Control: public, max-age=31536000, immutable',
    '/fonts/*\n  Cache-Control: public, max-age=2592000',
    '/sw.js\n  Cache-Control: no-cache',
    // The editing and upload tools must stay out of search. Not Disallowed in
    // robots.txt: a disallowed URL is never fetched, so the crawler would never
    // read this header and could still list the bare address.
    `/admin\n${NOINDEX}`,
    `/admin/*\n${NOINDEX}`,
    `/*.md\n${NOINDEX}`,
    `https://:subdomain.workers.dev/*\n${NOINDEX}`,
    `https://:version.:subdomain.workers.dev/*\n${NOINDEX}`,
  ];
  for (const host of SITE.noindexHosts) blocks.push(`https://${host}/*\n${NOINDEX}`);
  for (const p of ALL_POEMS.filter((x) => x.draft)) blocks.push(`/${p.id}\n${NOINDEX}`);
  return blocks.join('\n\n') + '\n';
}

function redirectsFile(): string {
  const lines = ['# Generated by integrations/site-output.ts from SITE.shortLinks.'];
  for (const [from, to] of Object.entries(SITE.shortLinks)) if (to) lines.push(`/${from} ${to} 302`);
  return lines.join('\n') + '\n';
}

/* What the service worker stores on install, so the site opens with no
   connection: every page a reader can reach, the bundles and styles they
   load, the fonts and icons. Not the admin tools (edited and reloaded — one
   launch stale there is a real confusion), not drafts, not the PDFs. */
function precacheable(url: string): boolean {
  if (url === '/sw.js' || url.startsWith('/admin') || url.startsWith('/pdf/') || url === '/404') return false;
  if (/^\/_(headers|redirects)$/.test(url) || /\.(md|map|txt|xml)$/.test(url)) return false;
  if (url.endsWith('.json') && !url.endsWith('.webmanifest')) return false;
  const drafts = new Set(ALL_POEMS.filter((p) => p.draft).map((p) => '/' + p.id));
  return !drafts.has(url);
}

async function buildServiceWorker(distDir: string, root: string): Promise<{ version: string; count: number }> {
  const files = (await walk(distDir)).map((f) => ({ abs: f, url: urlOf(relative(distDir, f)) }));
  const shell = files.filter((f) => precacheable(f.url)).sort((a, b) => (a.url < b.url ? -1 : 1));
  const hash = createHash('sha256');
  for (const f of shell) hash.update(f.url).update(await readFile(f.abs));
  const version = hash.digest('hex').slice(0, 12);
  const urls = shell.map((f) => f.url);
  const pages = shell.filter((f) => f.abs.endsWith('.html')).map((f) => f.url);
  const data = POEMS.map((p) => `/api/poems/${p.id}/data.js`);

  await build({
    entryPoints: [join(root, 'src/sw/sw.ts')],
    bundle: true,
    format: 'iife',
    target: 'es2022',
    minify: true,
    legalComments: 'none',
    outfile: join(distDir, 'sw.js'),
    define: {
      __SW_VERSION__: JSON.stringify(version),
      __PRECACHE__: JSON.stringify(urls),
      __SHELL_PAGES__: JSON.stringify(pages),
      __DATA_ASSETS__: JSON.stringify(data),
    },
    logLevel: 'warning',
  });
  return { version, count: urls.length };
}

export function siteOutput(): AstroIntegration {
  let root = process.cwd();
  return {
    name: 'asl-site-output',
    hooks: {
      'astro:config:done': ({ config }) => { root = fileURLToPath(config.root); },
      'astro:build:done': async ({ dir, logger }) => {
        const distDir = fileURLToPath(dir);
        await writeFile(join(distDir, '_headers'), headersFile());
        await writeFile(join(distDir, '_redirects'), redirectsFile());
        const sw = await buildServiceWorker(distDir, root);
        logger.info(`service worker ${sw.version}: ${sw.count} files precached`);
      },
    },
  };
}
